def rq3_gfg_rule_reusability(
  csv_fpaths: List[str],
  model_names: List[str],
  output_fpath: str,
):
  '''
  CSV is expected to have two columns:
  (COUNT, RULE_STR)
  as generated by e_experiments.e05_rq3_gfg_rule_reusability()

  NOTE rule indices must be consistent across CSV files!
  '''
  output_fpath = e_common.normalize_path(output_fpath)
  assert len(csv_fpaths) == 1, 'reimplement for multiple CSV files'

  all_counts = []
  for csv_fpath in csv_fpaths:
    csv_fpath = e_common.normalize_path(csv_fpath)
    reader = csv.reader(open(csv_fpath, 'r'))
    next(reader)  # Skip header row
    counts = []
    for row in reader:
      assert len(row) == 2, 'Expected two columns in CSV file'
      count = int(row[0])
      counts.append(count)
    # sort reuse rates in ascending order
    counts.sort()
    all_counts.append(counts)

  line_plot_series(
    series_list=all_counts,
    labels=model_names,
    title='Rule Reusability',
    x_label='Rule Index (sorted by reusability)',
    y_label='# of Uses',
    output_fpath=output_fpath,
  )


